// Writes src/styles/preflight.css: Tailwind's reset (tailwindcss/preflight.css) confined to the
// editor, so a page embedding it keeps its own styles. Every selector is put under the editor's
// root (.chem-app) or one of its overlays (.chem-overlay, which portal out to <body>); html and
// :host become those roots themselves. Selectors stay at zero specificity (:where), as in
// Tailwind, so utilities win. Run after updating Tailwind: node packages/react/scripts/scoped-preflight.mjs
import { readFileSync, writeFileSync } from "node:fs"
import { createRequire } from "node:module"

const SCOPE = ":where(.chem-app, .chem-overlay)"
const source = readFileSync(createRequire(import.meta.url).resolve("tailwindcss/preflight.css"), "utf8").replace(/\/\*[\s\S]*?\*\//g, "")

/** A selector confined to the editor; `*` and pseudo-elements also reach the root element itself. */
function scoped(selector) {
  const s = selector.trim()
  if (s === "html" || s === ":host") return [SCOPE]
  if (s === "*") return [SCOPE, `${SCOPE} *`]
  if (s.startsWith("::")) return [`${SCOPE}${s}`, `${SCOPE} *${s}`]
  return [`${SCOPE} ${s}`]
}

/** Splits CSS into top-level blocks, keeping at-rule blocks (with their nested rules) whole. */
function blocks(css) {
  const out = []
  let depth = 0
  let start = 0
  for (let i = 0; i < css.length; i++) {
    if (css[i] === "{") depth++
    else if (css[i] === "}" && --depth === 0) {
      out.push(css.slice(start, i + 1).trim())
      start = i + 1
    }
  }
  return out.filter(Boolean)
}

function rewrite(block) {
  const open = block.indexOf("{")
  const head = block.slice(0, open).trim()
  const body = block.slice(open + 1, -1)
  if (head.startsWith("@")) return `${head} {\n${blocks(body).map(rewrite).join("\n")}\n}`
  const selectors = [...new Set(head.split(/,(?![^(]*\))/).flatMap(scoped))]
  return `${selectors.join(",\n")} {${body}}`
}

const css = blocks(source).map(rewrite).join("\n\n")
writeFileSync(
  new URL("../src/styles/preflight.css", import.meta.url),
  `/* Generated by packages/react/scripts/scoped-preflight.mjs from tailwindcss/preflight.css (MIT): do not edit. */\n@layer base {\n${css}\n}\n`,
)
