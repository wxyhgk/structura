// Writes src/styles/tokens.css: a CSS variable for every colour the editor's interface uses
// (--c-<hex>, as its classes and style.css name them), its own colour in the light theme and
// darkColor's (src/components/theme.ts) in the dark one. Run after adding a colour:
// npm run tokens -w chem-structura (a test fails while the file is out of date).
import { readdirSync, readFileSync, writeFileSync } from "node:fs"
import { join } from "node:path"
import { fileURLToPath } from "node:url"
import { darkColor } from "../src/components/theme.ts"

const SRC = fileURLToPath(new URL("../src/", import.meta.url))
export const TOKENS = join(SRC, "styles", "tokens.css")

function sources(dir: string): string[] {
  return readdirSync(dir, { withFileTypes: true }).flatMap((entry) => {
    const path = join(dir, entry.name)
    if (entry.isDirectory()) return sources(path)
    return /\.(tsx?|css)$/.test(entry.name) && path !== TOKENS ? [path] : []
  })
}

/** The colours in use, sorted. */
export function usedColours(): string[] {
  const found = new Set<string>()
  for (const file of sources(SRC)) for (const match of readFileSync(file, "utf8").matchAll(/--c-([0-9a-f]{6})\b/g)) found.add(match[1])
  return [...found].sort()
}

/** tokens.css as it should be. */
export function tokensCss(colours = usedColours()): string {
  const light = colours.map((hex) => `  --c-${hex}: #${hex};`).join("\n")
  const dark = colours.map((hex) => `  --c-${hex}: ${darkColor(`#${hex}`)};`).join("\n")
  return `/* Generated by scripts/theme-tokens.ts: do not edit. Each colour the interface uses, as written for
   the light theme, and its dark-theme counterpart (darkColor in src/components/theme.ts). */
:where(.chem-app, .chem-overlay) {
${light}
}

:where(.chem-app, .chem-overlay):where(.chem-dark),
:where(.chem-dark) :where(.chem-app, .chem-overlay) {
${dark}
}
`
}

if (import.meta.url === `file://${process.argv[1]}`) {
  writeFileSync(TOKENS, tokensCss())
  console.log(`${TOKENS}: ${usedColours().length} colours`)
}
