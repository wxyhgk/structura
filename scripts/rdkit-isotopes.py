"""Regenerates packages/core/src/elements/isotopes.ts, the isotope masses formula.ts and
analysis.ts weigh atoms with: for every element RDKit knows, its most common isotope (the
one an exact mass uses), every isotope found in nature, and the radioisotopes chemists label
compounds with. Masses and abundances are RDKit's, so exact masses match its exactmw.

    python3 -m venv .venv && .venv/bin/pip install rdkit
    .venv/bin/python scripts/rdkit-isotopes.py > packages/core/src/elements/isotopes.ts
"""
import rdkit
from rdkit import Chem

# Radioisotopes drawn in labelled compounds, tracers and radiopharmaceuticals.
RADIO = {
    "H": [3], "C": [11, 14], "N": [13], "O": [15], "F": [18], "P": [32, 33], "S": [35], "Cl": [36],
    "Ca": [45], "Cr": [51], "Fe": [55, 59], "Co": [57, 58, 60], "Cu": [64, 67], "Ga": [67, 68],
    "Se": [75], "Br": [76, 77, 82], "Rb": [82], "Sr": [89, 90], "Y": [90], "Zr": [89], "Tc": [99],
    "In": [111], "I": [123, 124, 125, 131], "Xe": [133], "Sm": [153], "Lu": [177], "Re": [186, 188],
    "Tl": [201], "Pb": [212], "At": [211], "Bi": [213], "Ra": [223], "Ac": [225],
}

table = Chem.GetPeriodicTable()
lines = []
for z in range(1, 119):
    symbol = table.GetElementSymbol(z)
    common = table.GetMostCommonIsotope(z)
    # The heaviest elements have no measured mass in RDKit (0): no exact mass for them.
    if common <= 0 or table.GetMassForIsotope(z, common) <= 0:
        continue
    numbers = {common}
    for mass_number in range(max(1, common - 40), common + 41):
        if table.GetAbundanceForIsotope(z, mass_number) > 0:
            numbers.add(mass_number)
    numbers.update(RADIO.get(symbol, []))
    numbers = {n for n in numbers if table.GetMassForIsotope(z, n) > 0}
    pairs = ", ".join(f"{n}: {table.GetMassForIsotope(z, n):.10g}" for n in sorted(numbers))
    lines.append(f"  {symbol}: {{ {pairs} }},")

print(f"""// Generated by scripts/rdkit-isotopes.py from RDKit {rdkit.__version__}; do not edit.
// Each element's isotope masses by mass number: its most common isotope (the one an exact
// mass uses), every isotope found in nature, and the common radiolabels.

export const ISOTOPES: Readonly<Record<string, Readonly<Record<number, number>>>> = {{
{chr(10).join(lines)}
}}

/** Each element's most common isotope, the one an exact (monoisotopic) mass uses. */
export const COMMON_ISOTOPE: Readonly<Record<string, number>> = {{
{chr(10).join(f"  {table.GetElementSymbol(z)}: {table.GetMostCommonIsotope(z)}," for z in range(1, 119) if table.GetMostCommonIsotope(z) > 0 and table.GetMassForIsotope(z, table.GetMostCommonIsotope(z)) > 0)}
}}""")
